#!/usr/bin/env node
/**
 * Build `supabase/migrations/master-migration/LATEST_YYYYMMDD.sql` from the
 * feature migrations, in timestamp order.
 *
 *   npm run supabase:master          # --write: archive the old LATEST if it differs, write today's
 *   npm run supabase:master:check    # --check: exit 1 if LATEST is out of date
 *
 * `--check` compares everything after the first (date) line, so a LATEST
 * written on an earlier day still passes when the SQL matches.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const FEATURE_DIR = "supabase/migrations/feature-migrations";
const MASTER_DIR = "supabase/migrations/master-migration";
const LATEST_RE = /^LATEST_\d{8}\.sql$/;

function dateLine(yyyymmdd) {
  const iso = `${yyyymmdd.slice(0, 4)}-${yyyymmdd.slice(4, 6)}-${yyyymmdd.slice(6, 8)}`;
  return `-- Master migration. Creates an empty database at the ${iso} schema.`;
}

const HEADER = [
  `-- Generated by \`npm run supabase:master\` from ${FEATURE_DIR}/ in timestamp order.`,
  "-- Do not edit by hand. Do not apply this on a database that already ran those feature migrations.",
].join("\n");

export function todayStamp(now = new Date()) {
  const pad = (n) => String(n).padStart(2, "0");
  return `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}`;
}

/** Everything in LATEST except the date line. */
export function buildMasterBody(root) {
  const dir = join(root, FEATURE_DIR);
  const names = existsSync(dir)
    ? readdirSync(dir)
        .filter((name) => name.endsWith(".sql"))
        .sort()
    : [];
  const sections = names.map((name) => {
    const sql = readFileSync(join(dir, name), "utf8").trimEnd();
    return `-- ── ${name} ──\n\n${sql}\n`;
  });
  return `${HEADER}\n\n${sections.join("\n")}`;
}

function bodyOf(text) {
  const nl = text.indexOf("\n");
  return nl === -1 ? "" : text.slice(nl + 1);
}

export function listLatest(root) {
  const dir = join(root, MASTER_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => LATEST_RE.test(name))
    .sort();
}

/** Returns `{ ok, message }`. */
export function checkMaster(root) {
  const latest = listLatest(root);
  if (latest.length !== 1) {
    return { ok: false, message: `Expected exactly one ${MASTER_DIR}/LATEST_*.sql, found ${latest.length}.` };
  }
  const current = readFileSync(join(root, MASTER_DIR, latest[0]), "utf8");
  if (bodyOf(current) !== buildMasterBody(root)) {
    return {
      ok: false,
      message: `${MASTER_DIR}/${latest[0]} is out of date with ${FEATURE_DIR}/. Run: npm run supabase:master`,
    };
  }
  return { ok: true, message: `${MASTER_DIR}/${latest[0]} matches ${FEATURE_DIR}/.` };
}

function archiveTarget(archiveDir, name) {
  let target = join(archiveDir, name);
  for (let i = 2; existsSync(target); i += 1) {
    target = join(archiveDir, name.replace(/\.sql$/, `-${i}.sql`));
  }
  return target;
}

/** Returns the written path relative to root, or null when already current. */
export function writeMaster(root, stamp = todayStamp()) {
  const masterDir = join(root, MASTER_DIR);
  const archiveDir = join(masterDir, "archive");
  mkdirSync(archiveDir, { recursive: true });
  const body = buildMasterBody(root);
  const latest = listLatest(root);
  if (latest.length === 1 && bodyOf(readFileSync(join(masterDir, latest[0]), "utf8")) === body) {
    return null;
  }
  for (const name of latest) renameSync(join(masterDir, name), archiveTarget(archiveDir, name));
  const name = `LATEST_${stamp}.sql`;
  writeFileSync(join(masterDir, name), `${dateLine(stamp)}\n${body}`);
  return `${MASTER_DIR}/${name}`;
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const mode = process.argv[2];
  if (mode === "--check") {
    const { ok, message } = checkMaster(root);
    (ok ? console.log : console.error)(`→ ${message}`);
    process.exit(ok ? 0 : 1);
  }
  if (mode === "--write") {
    const written = writeMaster(root);
    console.log(written ? `→ wrote ${written}` : `→ ${basename(MASTER_DIR)} already current`);
    return;
  }
  console.error("Usage: node scripts/build-master-migration.mjs --write | --check");
  process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
